import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import path from 'node:path';

const root = process.cwd();
const read = (file) => readFile(path.join(root, file), 'utf8');

const [districts, map, mapStyles, matchups, pulseMap, globals] = await Promise.all([
  read('lib/ca-districts.ts'),
  read('components/district-map.tsx'),
  read('components/district-map.module.css'),
  read('components/race-matchups.tsx'),
  read('components/california-pulse-map.tsx'),
  read('app/globals.css'),
]);

// The map is the Proposition 50 plan, from a published source, not the 2021 lines.
assert.match(districts, /AB 604 \(2025\)/);
assert.match(districts, /Proposition 50/);
assert.match(districts, /Chapter 96, Statutes of 2025/);
assert.match(
  districts,
  /https:\/\/aelc\.assembly\.ca\.gov\/system\/files\/2025-08\/ab604\.zip|https:\/\/statewidedatabase\.org\/pub\/data\/d25\//,
);
assert.match(districts, /sha256 [0-9a-f]{64}/);
assert.match(districts, /Generated by scripts\/build-ca-districts\.mjs/);

const viewBox = districts.match(/CA_DISTRICT_VIEW_BOX = '0 0 (\d+) (\d+)'/);
assert.ok(viewBox, 'missing view box');
const [width, height] = [Number(viewBox[1]), Number(viewBox[2])];

const entries = [
  ...districts.matchAll(/\{ n: (\d+), x: ([\d.]+), y: ([\d.]+), r: ([\d.]+), d: '([^']+)' \}/g),
].map((m) => ({ n: Number(m[1]), x: Number(m[2]), y: Number(m[3]), r: Number(m[4]), d: m[5] }));

assert.deepEqual(
  entries.map((e) => e.n),
  Array.from({ length: 52 }, (_, i) => i + 1),
  'expected districts 1 to 52, once each, in order',
);

function rings(d) {
  const numbers = (text) => text.match(/-?(?:\d+\.?\d*|\.\d+)/g).map(Number);
  return d
    .split('z')
    .filter(Boolean)
    .map((part) => {
      assert.match(part, /^M[^Ml]+l[^Ml]+$/, 'each ring is one move and one run of relative lines');
      const [start, steps] = part.slice(1).split('l');
      let [x, y] = numbers(start);
      const ring = [[x, y]];
      const deltas = numbers(steps);
      assert.equal(deltas.length % 2, 0);
      for (let i = 0; i < deltas.length; i += 2) {
        x += deltas[i];
        y += deltas[i + 1];
        ring.push([x, y]);
      }
      return ring;
    });
}

function contains(shape, x, y) {
  let inside = false;
  for (const ring of shape) {
    for (let i = 0, j = ring.length - 1; i < ring.length; j = i, i += 1) {
      const [xi, yi] = ring[i];
      const [xj, yj] = ring[j];
      if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
    }
  }
  return inside;
}

const shapes = new Map(entries.map((e) => [e.n, rings(e.d)]));
for (const entry of entries) {
  const shape = shapes.get(entry.n);
  for (const ring of shape) {
    assert.ok(ring.length >= 3, `district ${entry.n} has a degenerate ring`);
    for (const [x, y] of ring) {
      assert.ok(x >= -0.05 && x <= width + 0.05 && y >= -0.05 && y <= height + 0.05, `district ${entry.n} leaves the view box`);
    }
  }
  // The point a lit district's ring is drawn around is inside that district
  // and no other, so a tap near it picks the right one.
  assert.ok(entry.r > 0, `district ${entry.n} has no room`);
  const holders = entries.filter((other) => contains(shapes.get(other.n), entry.x, entry.y)).map((o) => o.n);
  assert.deepEqual(holders, [entry.n], `district ${entry.n}'s point lies in ${holders.join(', ')}`);
}

// Interaction: the district of the race on show is lit, and a district can be picked.
assert.match(matchups, /<DistrictMap lit=\{shown\}/);
assert.match(map, /role="radiogroup"/);
assert.match(map, /role="radio"/);
assert.match(map, /aria-checked=\{district\.n === lit\}/);
assert.match(map, /onClick=\{pickAt\}/);
assert.match(map, /onKeyDown=\{step\}/);
assert.match(matchups, /type="button"/, 'buttons inside the signup form must not submit it');
assert.doesNotMatch(matchups, /<button(?![^>]*type="button")/);

// The page stays server-rendered: only the map and matchups are client code.
assert.doesNotMatch(pulseMap, /['"]use client['"]/);
assert.match(map, /^'use client';/);
for (const client of [map, matchups]) {
  assert.ok(
    !/^import (?!type )[^;]*from '@\/lib\/races'/m.test(client),
    'client code may only import types from lib/races, which reads the database',
  );
}

// No ambient flashing: nothing on the map loops, and motion stops for readers
// who ask for less of it.
assert.doesNotMatch(globals, /gcj-map-pulse/);
assert.doesNotMatch(globals, /\.ca-district/);
assert.doesNotMatch(mapStyles, /infinite/);
assert.match(mapStyles, /prefers-reduced-motion: reduce/);

console.log('ca-districts: 52 AB 604 districts, numbered 1 to 52, drawn and lit correctly');
