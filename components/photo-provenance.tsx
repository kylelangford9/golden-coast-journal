import Link from 'next/link';
import { ExternalLink, X } from 'lucide-react';

/**
 * Where a story's picture came from, one tap away from the picture.
 *
 * The Journal's claim is that every image is a real photograph or an official
 * graphic, credited, licensed and hosted by the Journal. The caption states the
 * credit; this card shows the rest of the record, so a reader can check the
 * claim against the original file rather than take it on trust.
 */
export function PhotoProvenance({
  label,
  alt,
  credit,
  provenanceUrl,
}: {
  label: string;
  alt: string;
  credit: string;
  provenanceUrl: string | null;
}) {
  const id = 'photo-about';
  return (
    <>
      <span className="photo-credit-line">
        {label} ·{' '}
        {provenanceUrl ? (
          <a href={provenanceUrl} target="_blank" rel="noreferrer">
            {credit}
          </a>
        ) : (
          credit
        )}
      </span>
      <button type="button" className="photo-about" popoverTarget={id}>
        About this image
      </button>
      <section
        id={id}
        popover="auto"
        className="photo-card"
        aria-labelledby={`${id}-title`}
      >
        <span className="photo-card-head">
          <strong id={`${id}-title`}>About this image</strong>
          <button
            type="button"
            className="person-card-close"
            popoverTarget={id}
            popoverTargetAction="hide"
            aria-label="Close"
          >
            <X size={16} aria-hidden="true" />
          </button>
        </span>
        <span className="photo-card-alt">{alt}</span>
        <span className="photo-card-row">
          <span>Type</span>
          {label}
        </span>
        <span className="photo-card-row">
          <span>Credit</span>
          {credit}
        </span>
        {provenanceUrl ? (
          <span className="photo-card-row">
            <span>Source</span>
            <a href={provenanceUrl} target="_blank" rel="noreferrer">
              Original file and licence{' '}
              <ExternalLink size={12} aria-hidden="true" />
            </a>
          </span>
        ) : null}
        <span className="photo-card-note">
          Every image in the Journal is a real photograph or an official
          graphic, credited and hosted by the Journal. None is generated by AI.{' '}
          <Link href="/standards">Our image standards</Link>
        </span>
      </section>
    </>
  );
}
